/** Responsibility: construct the Express application and mount versioned domain routers/middleware. */
import express from "express";
import cors from "cors";
import helmet from "helmet";
import { API_PREFIX } from "./config/constants";
import { errorHandler } from "./common/middlewares/errorHandler";
import { authRouter } from "./modules/auth/auth.routes";
import { catalogRouter } from "./modules/admin/catalog/catalog.routes";
import { studioRouter } from "./modules/admin/studio/studio.routes";
import { rulesRouter } from "./modules/admin/rules/rules.routes";
import { credibilityRouter } from "./modules/admin/credibility/credibility.routes";
import { governanceRouter } from "./modules/admin/governance/governance.routes";
import { registrationRouter } from "./modules/student/registration/registration.routes";
import { profileRouter } from "./modules/student/profile/profile.routes";
import { applicationsRouter } from "./modules/student/applications/applications.routes";
import { opportunitiesRouter } from "./modules/company/opportunities/opportunities.routes";
import { discoveryRouter } from "./modules/company/discovery/discovery.routes";
import { pipelineRouter } from "./modules/company/pipeline/pipeline.routes";
import { calibrationRouter } from "./modules/company/calibration/calibration.routes";
import { auditRouter } from "./modules/audit/audit.routes";
export const app = express();
app.use(helmet());
app.use(cors());
app.use(express.json({ limit: "32kb" }));
app.get("/health", (_req, res) => res.json({ status: "ok" }));
app.use(`${API_PREFIX}/auth`, authRouter);
app.use(`${API_PREFIX}/admin/catalog`, catalogRouter);
app.use(`${API_PREFIX}/admin/studio`, studioRouter);
app.use(`${API_PREFIX}/admin/rules`, rulesRouter);
app.use(`${API_PREFIX}/admin/credibility`, credibilityRouter);
app.use(`${API_PREFIX}/admin/governance`, governanceRouter);
app.use(`${API_PREFIX}/student/registration`, registrationRouter);
app.use(`${API_PREFIX}/student/profile`, profileRouter);
app.use(`${API_PREFIX}/student/applications`, applicationsRouter);
app.use(`${API_PREFIX}/company/opportunities`, opportunitiesRouter);
app.use(`${API_PREFIX}/company/discovery`, discoveryRouter);
app.use(`${API_PREFIX}/company/pipeline`, pipelineRouter);
app.use(`${API_PREFIX}/company/calibration`, calibrationRouter);
app.use(`${API_PREFIX}/audit`, auditRouter);
app.use(errorHandler);
